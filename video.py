    w_top, h_top = draw.textbbox((0, 0), top_text, font=font_top)[2], draw.textbbox((0, 0), top_text, font=font_top)[3]
    w_bottom, h_bottom = draw.textbbox((0, 0), bottom_text, font=font_bottom)[2], draw.textbbox((0, 0), bottom_text, font=font_bottom)[3]

    line_y_mid = TARGET_H - margin - 20 - h_bottom - LINE_SPACING
    draw.text((margin, TARGET_H - margin - 20 - h_bottom), bottom_text, font=font_bottom, fill=TEXT_COLOR)
    draw.text((margin, line_y_mid - h_top - LINE_SPACING), top_text, font=font_top, fill=TEXT_COLOR)

    if LINE_VARIANT == "LINE 2":
        draw.line([(margin-20, line_y_mid - h_top - 20), (margin-20, TARGET_H - margin - 10)], fill=LINE_COLOR, width=4)
        draw.line([(margin-20, line_y_mid - h_top - 20), (margin-20 + max(w_top, w_bottom)*0.3, line_y_mid - h_top - 20)], fill=LINE_COLOR, width=4)
