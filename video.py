def create_centered_info_card(lines, duration, is_intro=True):
    """Vytvoří černý snímek s centrovaným textem, znakem & a linkou v závěru."""
    img = Image.new("RGB", (TARGET_W, TARGET_H), color="black")
    draw = ImageDraw.Draw(img)

    def get_font(is_bold, is_italic, size):
        prefix = "/usr/share/fonts/truetype/liberation/LiberationSans"
        if is_bold and is_italic: path = f"{prefix}-BoldItalic.ttf"
        elif is_bold: path = f"{prefix}-Bold.ttf"
        elif is_italic: path = f"{prefix}-Italic.ttf"
        else: path = f"{prefix}-Regular.ttf"
        try:
            return ImageFont.truetype(path, int(size))
        except:
            return ImageFont.load_default()

    # Velikosti fontů: hlavní vs kontaktní (80%)
    font_size_main = FONT_SIZE_MAKLER
    font_size_small = FONT_SIZE_MAKLER * 0.8

    # Sestavení řádků a přiřazení stylů
    # Každý prvek: (text, font)
    content = []
    content.append((lines[0], get_font(MAKLER_BOLD, MAKLER_ITALIC, font_size_main))) # Jméno
    content.append(("&", get_font(True, False, font_size_main)))                       # Znak &
    content.append((lines[1], get_font(RK_BOLD, RK_ITALIC, font_size_main)))         # RK Název

    if not is_intro:
        for line in lines[2:]:
            is_email = "@" in line
            # Použití menšího písma (80%) pro kontaktní údaje
            content.append((line, get_font(False, is_email, font_size_small)))

    # Výpočet rozměrů
    line_h = draw.textbbox((0, 0), "Ay", font=get_font(True, False, font_size_main))[3] + 20
    total_h = len(content) * line_h
    if not is_intro: total_h += 30

    curr_y = (TARGET_H - total_h) // 2
    max_w = max([draw.textbbox((0, 0), c[0], font=c[1])[2] for c in content])

    for i, (text, font) in enumerate(content):
        w = draw.textbbox((0, 0), text, font=font)[2]
        draw.text(((TARGET_W - w) // 2, curr_y), text, font=font, fill=TEXT_COLOR)

        # Linka v závěru pod RK Názvem (3. řádek)
        if not is_intro and i == 2:
            curr_y += line_h
            l_len = max_w * 1.1
            draw.line([((TARGET_W - l_len)//2, curr_y), ((TARGET_W + l_len)//2, curr_y)], fill=LINE_COLOR, width=4)
            curr_y += 15

        curr_y += line_h

    return ImageClip(np.array(img)).set_duration(duration)

def draw_text_overlay(image_np, text_str):
    img = Image.fromarray(image_np).convert("RGBA")
    draw = ImageDraw.Draw(img)
    margin = 50

    try:
        font_top = ImageFont.truetype("/usr/share/fonts/truetype/liberation/LiberationSans-Bold.ttf", FONT_SIZE_TOP)
        font_bottom = ImageFont.truetype("/usr/share/fonts/truetype/liberation/LiberationSans-Regular.ttf", FONT_SIZE_BOTTOM)
    except:
        font_top = font_bottom = ImageFont.load_default()

    parts = text_str.split(";")
    top_text, bottom_text = parts[0].strip(), parts[1].strip() if len(parts) > 1 else ""

    bbox_t = draw.textbbox((0, 0), top_text, font=font_top)
    bbox_b = draw.textbbox((0, 0), bottom_text, font=font_bottom)
    w_top, h_top = bbox_t[2]-bbox_t[0], bbox_t[3]-bbox_t[1]
    w_bottom, h_bottom = bbox_b[2]-bbox_b[0], bbox_b[3]-bbox_b[1]

    line_length = max(w_top, w_bottom)
    y_bottom_base = TARGET_H - margin - 20

    line_y_mid = y_bottom_base - h_bottom - LINE_SPACING
    y_top_base = line_y_mid - h_top - LINE_SPACING

    draw.text((margin, y_bottom_base - h_bottom), bottom_text, font=font_bottom, fill=TEXT_COLOR)
    draw.text((margin, y_top_base), top_text, font=font_top, fill=TEXT_COLOR)

    y_top_border = y_top_base - 10
    y_bottom_border = y_bottom_base + 10
    text_block_height = y_bottom_border - y_top_border

    if LINE_VARIANT == "LINE 1":
        draw.line([(margin, line_y_mid), (margin + line_length, line_y_mid)], fill=LINE_COLOR, width=3)
    elif LINE_VARIANT == "LINE 2":
        draw.line([(margin - 15, y_top_border), (margin - 15, y_bottom_border)], fill=LINE_COLOR, width=3)
        draw.line([(margin - 15, y_top_border), (margin - 15 + (line_length * 0.25), y_top_border)], fill=LINE_COLOR, width=3)
        draw.line([(margin - 15, y_bottom_border), (margin + line_length, y_bottom_border)], fill=LINE_COLOR, width=3)

    logo_path = globals().get('LOGO_FILE')
    if logo_path and os.path.exists(logo_path):
        logo = Image.open(logo_path).convert("RGBA")
        aspect = logo.width / logo.height
        new_h = int(text_block_height)
        new_w = int(new_h * aspect)
        logo_resized = logo.resize((new_w, new_h), Image.Resampling.LANCZOS)
        img.paste(logo_resized, (TARGET_W - margin - new_w, y_top_border), logo_resized)

    return np.array(img.convert("RGB"))

def apply_smooth_smart_motion(img_path, duration, text_overlay=""):
    img = Image.open(img_path).convert("RGB")
    img_w, img_h = img.size

    def make_frame(t):
        progress = t / duration
        curr_zoom = 1 + (ZOOM_SPEED * progress)
        sw = int(TARGET_W / curr_zoom)
        sh = int(TARGET_H / curr_zoom)
        x = (img_w - sw) // 2
        y = (img_h - sh) // 2
        frame = img.crop((x, y, x + sw, y + sh)).resize((TARGET_W, TARGET_H), Image.Resampling.LANCZOS)
        frame_np = np.array(frame)
        if text_overlay:
            frame_np = draw_text_overlay(frame_np, text_overlay)
        return frame_np

    return ImageClip(make_frame(0)).set_duration(duration).set_make_frame(make_frame)

